# -*- coding: utf-8 -*-
"""Write js/bank.js from bank/question_bank.json so the game can load the questions with a plain <script> tag
(works from GitHub Pages and when index.html is opened straight from disk). Re-run after any change to the bank.
Run: python3 -E bank/build_bank_js.py
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
bank = json.load(open(os.path.join(HERE, "question_bank.json"), encoding="utf-8"))
out = {"version": bank["version"], "categories": bank["categories"], "values": bank["values"], "items": bank["items"]}
body = json.dumps(out, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
with open(os.path.join(os.path.dirname(HERE), "js", "bank.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by bank/build_bank_js.py from bank/question_bank.json. Do not edit by hand.\n")
    f.write("window.BANK=" + body + ";\n")
print("wrote js/bank.js:", len(out["items"]), "items")
